import { chromium, devices } from 'playwright';
import { mkdirSync } from 'node:fs';
mkdirSync('e2e/shots', { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['Pixel 5'] });
const page = await ctx.newPage();
const log = [];
page.on('response', (r) => { if (/firestore|functions\/v1|facebook/.test(r.url())) log.push(`${r.status()} ${r.url().split('?')[0]}`); });
const cdp = await ctx.newCDPSession(page);
await cdp.send('Network.enable');
await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 150, downloadThroughput: 1.6 * 1024 * 1024 / 8, uploadThroughput: 750 * 1024 / 8 });
const t0 = Date.now();
await page.goto('https://bigpayrolls.com/website-quote/?utm_source=claude&utm_medium=test&utm_campaign=live-check&utm_content=smoke', { waitUntil: 'load' });
const lcp = await page.evaluate(() => new Promise((ok) => new PerformanceObserver((l) => { const e = l.getEntries(); ok(Math.round(e[e.length - 1].startTime)); }).observe({ type: 'largest-contentful-paint', buffered: true })));
console.log(`LIVE slow-4G: load ${Date.now() - t0} ms, largest paint ${lcp} ms`);
await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
await page.getByRole('button', { name: 'Allow' }).click();
await page.fill('#q-name', 'TEST - website check (ignore)');
await page.fill('#q-phone', '9000000000');
await page.locator('#quote label').filter({ hasText: /^Other$/ }).click();
await page.locator('#quote label').filter({ hasText: /^Not sure$/ }).click();
await page.fill('#q-msg', 'Automatic test of the live page. Please mark as Not interested.');
await page.getByRole('checkbox').check();
await page.getByRole('button', { name: 'Get my free quote' }).first().click();
await page.getByText("Thanks! We'll call you within 24 hours.").waitFor({ timeout: 20000 });
console.log('LIVE thank-you message shown');
await page.waitForTimeout(4000);
const fb = await page.evaluate(() => typeof window.fbq === 'function' && window.fbq.loaded);
console.log('LIVE pixel loaded after Allow:', fb);
await page.screenshot({ path: 'e2e/shots/live-thanks.png' });
console.log(log.join('\n'));
await b.close();
